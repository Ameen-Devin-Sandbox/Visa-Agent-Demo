    lines.append("")
    lines.append("Encodes the specific time limits from Visa Core Rules Section 11 for each")
    lines.append("dispute condition, including regional exceptions.")
    lines.append('"""')
    lines.append("")
    lines.append("from datetime import date, datetime, timedelta")
    lines.append("")
    lines.append("from src.models.dispute import TimeLimit")
    lines.append("from src.models.enums import DisputeCondition, Region")
    lines.append("")
    lines.append("DateLike = date | datetime")
    lines.append("")

    # DISPUTE_TIME_LIMITS
    lines.append("# Time limits encoded from Visa Core Rules Section 11")
    lines.append("# Each condition has a base time limit and optional regional exceptions")
    lines.append("DISPUTE_TIME_LIMITS: dict[DisputeCondition, TimeLimit] = {")

    condition_enum_map = _condition_enum_map()
    for cond_code, tl in data["dispute_time_limits"].items():
        enum_name = condition_enum_map.get(cond_code)
        if enum_name is None:
            continue
        region_ex = tl.get("region_exceptions", {})
        region_str = repr(region_ex) if region_ex else ""
        lines.append(f"    DisputeCondition.{enum_name}: TimeLimit(")
        lines.append(f"        calendar_days={tl['calendar_days']},")
        lines.append(f'        from_event="{tl["from_event"]}",')
        if region_ex:
            lines.append(f"        region_exceptions={region_str},")
        lines.append(f'        description="{tl["description"]}",')
