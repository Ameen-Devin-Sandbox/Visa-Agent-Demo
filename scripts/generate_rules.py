#!/usr/bin/env python3
"""Generate Python rule files from YAML schemas.

Reads the YAML files from rules/generated/ and produces the Python files
in src/rules/. Generated files include an auto-generation header comment.

Usage:
    python scripts/generate_rules.py              # Regenerate all rule files
    python scripts/generate_rules.py --check      # Check if files are up to date
"""

import argparse
import sys
from pathlib import Path

import yaml

PROJECT_ROOT = Path(__file__).resolve().parent.parent
GENERATED_DIR = PROJECT_ROOT / "rules" / "generated"
RULES_DIR = PROJECT_ROOT / "src" / "rules"

HEADER_TEMPLATE = '''\
# THIS FILE IS AUTO-GENERATED from rules/generated/{yaml_file}
# DO NOT EDIT MANUALLY. Run `python scripts/generate_rules.py` to regenerate.
# Source: Visa Core Rules {version}
'''


def load_yaml(name: str) -> dict:
    """Load a YAML file from the generated directory."""
    path = GENERATED_DIR / f"{name}.yaml"
    if not path.exists():
        print(f"Error: {path} not found.", file=sys.stderr)
        sys.exit(1)
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def header(yaml_file: str, version: str) -> str:
    """Generate the auto-generation header comment."""
    return HEADER_TEMPLATE.format(yaml_file=yaml_file, version=version)


