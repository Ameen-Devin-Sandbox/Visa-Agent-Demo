def main() -> None:
    parser = argparse.ArgumentParser(description="Generate Python rule files from YAML schemas")
    parser.add_argument("--check", action="store_true", help="Check if files are up to date (exit 1 if not)")
    args = parser.parse_args()

    generators = {
        "time_limits": generate_time_limits,
        "validity": generate_validity,
        "documentation": generate_documentation,
        "compelling_evidence": generate_compelling_evidence,
        "categorizer_data": generate_categorizer,
    }

    all_up_to_date = True
    for name, generator in generators.items():
        content = generator()
        output_path = RULES_DIR / f"{name}.py"

        if args.check:
            if output_path.exists():
                existing = output_path.read_text(encoding="utf-8")
                if existing != content:
                    print(f"OUT OF DATE: {output_path}")
                    all_up_to_date = False
                else:
                    print(f"Up to date: {output_path}")
            else:
                print(f"MISSING: {output_path}")
                all_up_to_date = False
        else:
            output_path.write_text(content, encoding="utf-8")
            print(f"Generated {output_path}")

    if args.check and not all_up_to_date:
        sys.exit(1)


if __name__ == "__main__":
    main()
