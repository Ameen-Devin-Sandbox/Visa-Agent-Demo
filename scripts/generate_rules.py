    lines.append("    _DOC_DATA: dict[str, Any] = yaml.safe_load(_f)")
    lines.append("")
    lines.append("")
    lines.append("def _build_requirements() -> dict[DisputeCondition, list[DocumentationRequirement]]:")
    lines.append('    """Build the DOCUMENTATION_REQUIREMENTS dict from YAML data."""')
    lines.append("    result: dict[DisputeCondition, list[DocumentationRequirement]] = {}")
    lines.append('    for cond_code, reqs in _DOC_DATA.get("requirements", {}).items():')
    lines.append("        try:")
    lines.append("            condition = DisputeCondition(cond_code)")
    lines.append("        except ValueError:")
    lines.append("            continue")
    lines.append("        result[condition] = [")
    lines.append("            DocumentationRequirement(")
    lines.append('                requirement_id=r["requirement_id"],')
    lines.append('                description=r["description"],')
    lines.append('                is_mandatory=r["is_mandatory"],')
    lines.append('                rule_section=r["rule_section"],')
    lines.append("                condition=cond_code,")
    lines.append("            )")
    lines.append("            for r in reqs")
    lines.append("        ]")
    lines.append("    return result")
    lines.append("")
    lines.append("")
    lines.append("DOCUMENTATION_REQUIREMENTS = _build_requirements()")
    lines.append("")
    lines.append("")
    lines.append("def _build_letter_requirements() -> tuple[list[str], list[str]]:")
    lines.append('    """Build cardholder letter requirements from YAML data."""')
    lines.append('    letter_reqs = _DOC_DATA.get("cardholder_letter_requirements", {})')
    lines.append('    cat_10 = letter_reqs.get("category_10", [])')
    lines.append('    cat_13 = letter_reqs.get("category_13", [])')
    lines.append("    return cat_10, cat_13")
    lines.append("")
    lines.append("")
    lines.append("CATEGORY_10_LETTER_REQUIREMENTS, CATEGORY_13_LETTER_REQUIREMENTS = _build_letter_requirements()")
