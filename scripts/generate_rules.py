    lines.append("")
    lines.append("@dataclass")
    lines.append("class DocumentationRequirement:")
    lines.append('    """A required document or certification for a dispute condition."""')
    lines.append("")
    lines.append("    requirement_id: str")
    lines.append("    description: str")
    lines.append("    is_mandatory: bool")
    lines.append("    rule_section: str")
    lines.append("    condition: str")
    lines.append("")
    lines.append("")
    lines.append("@dataclass")
    lines.append("class DocumentationCheckResult:")
    lines.append('    """Result of checking documentation requirements."""')
    lines.append("")
    lines.append("    is_complete: bool")
    lines.append("    met_requirements: list[str]")
    lines.append("    missing_requirements: list[str]")
    lines.append("    details: str")
    lines.append("")
    lines.append("")
    lines.append("# Load documentation rules from YAML at import time")
    lines.append('_YAML_PATH = Path(__file__).resolve().parent.parent.parent / "rules" / "generated" / "documentation.yaml"')
