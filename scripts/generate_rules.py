    lines.append("        try:")
    lines.append("            condition = DisputeCondition(cond_code)")
    lines.append("        except ValueError:")
    lines.append("            continue")
    lines.append('        result[condition] = [FraudTypeCode(c) for c in req_data["allowed_codes"]]')
    lines.append("    return result")
    lines.append("")
    lines.append("")
    lines.append("_FRAUD_CODE_REQUIREMENTS = _build_fraud_code_requirements()")
    lines.append("")
    lines.append("")

    # check_fraud_type_code_requirement function
    lines.append("def check_fraud_type_code_requirement(case: DisputeCase) -> DocumentationCheckResult:")
    lines.append('    """Check that the correct fraud type code was reported for Category 10 conditions.')
    lines.append("")
    lines.append("    Per Section 11.7.2.2: Before initiating a Dispute, an Issuer must report")
